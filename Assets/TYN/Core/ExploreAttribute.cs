namespace EldritchMile.Core
{
    /// <summary>
    /// C17：機率卡與互動目標的屬性。**這不是元素，是心靈結構。**
    ///
    /// 【怎麼讀這個系統】目標的屬性代表「這個難題吃哪一種心智」，
    /// 不是「誰打贏誰」。所以相剋的語意是「這種心智對這種問題有沒有用」，
    /// 而不是元素環。設計相剋規則時務必守住這個框架，否則會不小心做成寶可夢。
    ///
    /// ────────────────────────────────────────────────────────
    /// 【Q7b 定案 2026-08-21】改用佛洛伊德的心靈三分。
    ///
    /// 舊名 → 新名（**數值完全沒動，所以卡牌與物件一個都不用重指**）：
    ///   Intuition(1) 直覺        → Id(1)        本我
    ///   Logic(2)     邏輯        → Superego(2)  超我
    ///   Insight(3)   批判與創造  → Ego(3)       自我
    ///
    /// 【為什麼是這個對法】現有的相剋表本來就是「1 和 2 對立、3 是橋」，
    /// 而佛洛伊德那套剛好同構：**本我與超我對立，自我調停**。
    /// 所以相剋規則一條都不用改，牌框也不用重指 —— 純粹是換名字。
    ///
    /// 對成「本我獨立、自我與超我對立」的話功能一樣，但要改相剋表 ＋ 對調 12 張卡的牌框，
    /// 而且會跟玩家腦子裡既有的認知打架（大家都知道調停的是自我）。
    ///
    /// 【為什麼用現成的三元組】前幾版（直覺／邏輯／批判與創造、情緒／思辨）都是自訂分類，
    /// 玩家要重新學「這三個是什麼關係」。佛洛伊德那套**玩家腦子裡已經有這張表了**，
    /// 而且與 SAN、心智碎裂的題材是同一件事的兩個面。
    ///
    /// ────────────────────────────────────────────────────────
    /// 【顏色是對外的識別】美術資產依顏色命名（`機率牌框紅/藍`），玩家看不到屬性的名字。
    /// **紅藍是最強的對立組合**，所以留給真正對立的那一對（本我／超我）；
    /// 綠色給調停的自我 —— 它本來就是「什麼都沾一點」。
    ///
    /// ⚠️ **這裡的數值不要動**。序列化資料存的是整數（`attribute: 3`），
    /// 數值一改所有卡牌與物件就全部對錯屬性，而且不會有任何錯誤訊息。
    /// 顯示名要改的話改 <see cref="AttributeChartData"/> 上的欄位，不要動這裡。
    /// </summary>
    public enum ExploreAttribute
    {
        /// <summary>無（黑白）。目標為此值時不吃相剋，一律視為相符。</summary>
        None = 0,

        /// <summary>
        /// 本我（紅）。慾望、衝動、不經思索的驅力。與 <see cref="Superego"/> 互斥。
        /// </summary>
        Id = 1,

        /// <summary>
        /// 超我（藍）。戒律、規範、應當如何。與 <see cref="Id"/> 互斥。
        /// </summary>
        Superego = 2,

        /// <summary>
        /// 自我（綠）。夾在慾望與戒律之間斡旋的那一個 ——
        /// **兩邊都沾得上，所以對誰都不會完全無效，但也很少完美相符。**
        /// 它存在的目的是避免玩家抽到完全不能操作的牌。
        /// </summary>
        Ego = 3,
    }

    /// <summary>
    /// C19：相剋效果。三級，**沒有 2×**。
    ///
    /// 卡片自身的 successProbability 就是機率上限，相剋只會往下扣 ——
    /// 這是懲罰制，不是寶可夢那種雙向增減。實作時不要自作主張加獎勵層。
    /// </summary>
    public enum Effectiveness
    {
        /// 1.0× 相符
        Match = 0,

        /// 0.5× 模糊相關。
        /// 存在目的是「避免抽到的卡完全不能操作」，所以應該是常見情況。
        Partial = 1,

        /// 0.0× 無效。
        /// 因為 Partial 就是為了避免死鎖而設，所以 None 應該少用，
        /// 只保留給設計上真的要封死的組合。
        None = 2,
    }
}
