namespace EldritchMile.Core
{
    /// <summary>
    /// C17：機率卡與互動目標的屬性。**這不是元素，是思考模式。**
    ///
    /// 【怎麼讀這個系統】目標的屬性代表「這個難題吃哪一種腦袋」，
    /// 不是「誰打贏誰」。所以相剋的語意是「這種思路對這種問題有沒有用」，
    /// 而不是元素環。設計相剋規則時務必守住這個框架，否則會不小心做成寶可夢。
    ///
    /// 【顏色是對外的識別】美術資產依顏色命名（`機率牌框紅/藍`），
    /// 顯示名之後可能隨世界觀改動，但**這裡的 ID 與數值不要動** ——
    /// 序列化資料存的是整數（`attribute: 3`），數值一改所有卡牌與物件就全部對錯屬性。
    ///
    /// 【Q7a 定案 2026-08-15】名稱從 AttrA~D 佔位值改為機制名。
    ///
    /// 舊卡牌檔名 → 新屬性（依當時**既有牌框美術**對應，所以卡的顏色不必重指）：
    ///   explore_B_*（紅框）→ Intuition(1)
    ///   explore_C_*（藍框）→ Logic(2)
    ///   explore_A_*（原 plain 框）→ Insight(3)，牌框已改指新做的綠框
    ///   AttrD 移除（全專案無人使用）
    ///
    /// ⚠️ 注意這不是 A→1、B→2、C→3 的直覺對應 —— 檔名字母與數值刻意錯開，
    /// 是為了讓紅／藍卡沿用既有牌框。看到舊資料時不要照字母順序推。
    /// </summary>
    public enum ExploreAttribute
    {
        /// <summary>無（黑白）。目標為此值時不吃相剋，一律視為相符。</summary>
        None = 0,

        /// <summary>直覺（紅）。跳躍式的直觀，不經推演。與 Logic 互斥。</summary>
        Intuition = 1,

        /// <summary>邏輯（藍）。逐步推演、規則與結構。與 Intuition 互斥。</summary>
        Logic = 2,

        /// <summary>
        /// 批判與創造（綠）。質疑前提並提出新解 —— 兩種模式都用得上，
        /// 所以對誰都不會完全無效，但也很少完美相符。
        /// </summary>
        Insight = 3,
    }

    /// <summary>
    /// C19：相剋效果。三級，**沒有 2×**。
    ///
    /// 卡片自身的 successProbability 就是機率上限，相剋只會往下扣 ——
    /// 這是懲罰制，不是寶可夢那種雙向增減。實作時不要自作主張加獎勵層。
    /// </summary>
    public enum Effectiveness
    {
        /// 1.0× 相符
        Match = 0,

        /// 0.5× 模糊相關。
        /// 存在目的是「避免抽到的卡完全不能操作」，所以應該是常見情況。
        Partial = 1,

        /// 0.0× 無效。
        /// 因為 Partial 就是為了避免死鎖而設，所以 None 應該少用，
        /// 只保留給設計上真的要封死的組合。
        None = 2,
    }
}
