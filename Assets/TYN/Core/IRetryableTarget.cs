namespace EldritchMile.Core
{
    /// <summary>
    /// 手牌用盡後，可以「付出全域代價」再來一輪的目標。
    ///
    /// 【為什麼另開一個介面而不是塞進 IProbabilityTarget】不是每個判定目標都能重試 ——
    /// 一般物件失敗就是失敗。讓不能重試的目標被迫實作一堆空方法，
    /// 只會讓「這個東西到底能不能重試」變得看不出來。
    ///
    /// 【局部 vs 全域】C18⑤ 的「手牌數 = 嘗試次數上限」是**局部**資源制。
    /// 重試之所以需要**全域**代價（道具／HP／SAN），是因為免費的額外嘗試
    /// 會直接把那個上限廢掉 —— 玩家可以無限重來，局部限制就不存在了。
    ///
    /// 【重試語意】付出代價後衰減重置回初始、手牌重抽，之後機率照樣逐次衰減。
    /// **嘗試次數不重置** —— 衰減既然重置了，「總共耗掉多少」就成了唯一還看得見的
    /// 代價紀錄，而且它正好是遞增代價的依據。
    /// </summary>
    public interface IRetryableTarget
    {
        /// <summary>
        /// 現在能不能提供重試。
        /// 【注意】這裡回報 true 只代表「這個物件設定成可重試」，
        /// **不代表玩家付得起** —— 付不付得起由 TryPayForRetry() 當場判斷。
        /// </summary>
        bool CanOfferRetry { get; }

        /// <summary>
        /// 給玩家看的詢問文字，要**含代價**。
        /// 沒有金額的「要再試一次嗎？」是個假選擇 —— 玩家無從判斷划不划算。
        /// </summary>
        string BuildRetryPrompt();

        /// <summary>
        /// 實際付款。付得起就扣掉並回傳 true；付不起回傳 false（環節照常結束）。
        /// ⚠️ 這支有副作用，只能在玩家已經按下「是」之後呼叫一次。
        /// </summary>
        bool TryPayForRetry();

        /// <summary>付款成功後把狀態回到初始（衰減重置）。</summary>
        void ResetForRetry();
    }
}
